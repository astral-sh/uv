/// Download the released compiler and reuse it offline for optimized, hash-based bytecode.
#[cfg(feature = "test-r2")]
#[test]
fn native_bytecode_download() -> Result<()> {
    let context = uv_test::test_context!("3.12")
        .with_env("PYTHONOPTIMIZE", "2")
        .with_env("PYC_INVALIDATION_MODE", "CHECKED_HASH")
        .with_env("PYTHONPYCACHEPREFIX", "")
        .with_env("PYTHONNODEBUGRANGES", "");
    let (filename, wheel) = WheelBuilder::new(&"example".parse()?, &"1.0.0".parse()?)
        .files(&[(
            "example/module.py",
            "\"\"\"Module documentation.\"\"\"\nassert False\nvalue = 42\n",
        )])
        .build();
    let wheel_path = context.temp_dir.join(filename);
    fs_err::write(&wheel_path, wheel)?;
    context
        .temp_dir
        .child("requirements.txt")
        .write_str(&wheel_path.display().to_string())?;

    uv_snapshot!(context.filters(), context.pip_install()
        .arg(&wheel_path)
        .arg("--compile-bytecode")
        .arg("--preview-features").arg("native-bytecode"), @"
    exit_code: 0 (success)
    ----- stderr -----
    Resolved 1 package in [TIME]
    Prepared 1 package in [TIME]
    Installed 1 package in [TIME]
    Bytecode compiled 2 files in [TIME]
     + example==1.0.0 (from file://[TEMP_DIR]/example-1.0.0-py3-none-any.whl)
    ");

    let bytecode = context
        .site_packages()
        .join("example/__pycache__/module.cpython-312.opt-2.pyc");
    // PEP 552 sets both the hash-based and check-source flags for checked hashes.
    assert_eq!(&fs_err::read(&bytecode)?[4..8], &[3, 0, 0, 0]);
    let compiled = fs_err::metadata(&bytecode)?.modified()?;
    uv_snapshot!(context.filters(), context.pip_sync()
        .arg("requirements.txt")
        .arg("--offline")
        .arg("--compile-bytecode")
        .arg("--preview-features").arg("native-bytecode"), @"
    exit_code: 0 (success)
    ----- stderr -----
    Resolved 1 package in [TIME]
    Bytecode compiled 0 files in [TIME]
    ");
    assert_eq!(fs_err::metadata(&bytecode)?.modified()?, compiled);
    fs_err::remove_file(&bytecode)?;

    uv_snapshot!(context.filters(), context.pip_sync()
        .arg("requirements.txt")
        .arg("--offline")
        .arg("--compile-bytecode")
        .arg("--preview-features").arg("native-bytecode"), @"
    exit_code: 0 (success)
    ----- stderr -----
    Resolved 1 package in [TIME]
    Bytecode compiled 1 file in [TIME]
    ");

    // Execute the generated bytecode directly so Python cannot compile the source itself.
    uv_snapshot!(context.python_command()
        .arg("-c")
        .arg("import runpy, sys; module = runpy.run_path(sys.argv[1]); print(module['value'], module['__doc__'])")
        .arg(&bytecode), @"
    exit_code: 0 (success)
    ----- stdout -----
    42 None
    ");
    Ok(())
}

