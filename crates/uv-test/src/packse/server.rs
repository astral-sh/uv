//! A per-test wiremock server that serves packse scenario packages.
//!
//! Each [`PackseServer`] reads a single scenario TOML file and serves:
//! - PEP 691 Simple API at `/simple/{package}/`
//! - Distribution downloads at `/files/{filename}`
//!
//! Cached build dependencies are exposed through the same `/simple/*` and
//! `/files/*` routes as scenario packages.

use std::collections::{BTreeMap, HashMap};
use std::path::Path;
use std::str::FromStr;
use std::sync::Arc;

use serde_json::json;
use wiremock::{
    Mock, MockServer, Request, ResponseTemplate,
    matchers::{header_exists, method, path},
};

use uv_distribution_filename::{VariantLabel, WheelFilename};
use uv_distribution_types::{PEP_825_SCHEMA, PEP_850_SCHEMA};
use uv_normalize::PackageName;
use uv_pep440::VersionSpecifiers;

use crate::http_server::{HttpServer, content_type_for_filename};
use crate::vendor::{VendorArtifact, vendor_artifacts};

use super::scenario::{
    ArtifactMetadata, PackageMetadata, Scenario, VariantWheel, Variants, WheelTag,
};
use super::scenarios_dir;
use super::wheel::{DEFAULT_WHEEL_TAG, WheelBuilder, generate_sdist, sha256_hex};

const PACKSE_UPLOAD_TIME: &str = "2024-03-24T00:00:00Z";

/// Information about a file listed by the Simple API.
struct IndexFile {
    filename: String,
    sha256: String,
    distribution: Option<DistributionMetadata>,
}

/// Metadata for a distribution file, omitted for a release's `variants.json` sidecar.
#[derive(Default)]
struct DistributionMetadata {
    requires_python: Option<VersionSpecifiers>,
    upload_time: Option<String>,
    yanked: bool,
}

enum FileData {
    Bytes(Arc<[u8]>),
    Vendor(&'static VendorArtifact),
}

impl FileData {
    fn bytes(&self) -> anyhow::Result<Arc<[u8]>> {
        match self {
            Self::Bytes(bytes) => Ok(Arc::clone(bytes)),
            Self::Vendor(artifact) => artifact.bytes(),
        }
    }
}

/// The complete pre-indexed database for a server instance.
#[derive(Default)]
struct ServerIndex {
    /// Simple API: normalized package name → list of index files.
    packages: HashMap<PackageName, Vec<IndexFile>>,
    /// File downloads: filename → generated bytes or a lazy vendored artifact.
    files: HashMap<String, FileData>,
}

/// A running mock PyPI server for a single packse scenario.
///
/// The server runs on a background thread with its own single-threaded tokio runtime.
/// When [`PackseServer`] is dropped, the background thread and server are shut down.
pub struct PackseServer {
    server: HttpServer,
    index: Arc<ServerIndex>,
}

impl PackseServer {
    /// Load a scenario from a TOML path (relative to the vendored scenarios directory)
    /// and start a mock server for it.
    pub fn new(scenario_path: &str) -> Self {
        let full_path = scenarios_dir().join(scenario_path);
        let scenario =
            Scenario::from_path(&full_path).expect("vendored Packse scenario should parse");
        Self::from_scenario(&scenario)
    }

    /// Start a mock server with no packages (only cached build dependencies).
    ///
    /// Useful as a dummy index that will 404 for any non-cached package lookup.
    pub fn empty() -> Self {
        Self::from_scenario(&Scenario::empty())
    }

    /// Start a mock server for the given scenario.
    pub fn from_scenario(scenario: &Scenario) -> Self {
        Self::start(scenario, true)
    }

    /// Start a mock server that omits hashes from the Simple API, mimicking indexes that don't
    /// provide hashes, such as HTML-only indexes.
    pub fn from_scenario_without_hashes(scenario: &Scenario) -> Self {
        Self::start(scenario, false)
    }

    fn start(scenario: &Scenario, hashes: bool) -> Self {
        let index = Arc::new(ServerIndex::new(scenario));
        let server_index = Arc::clone(&index);
        let server = HttpServer::start(move |request, server_uri| {
            handle_request(request, server_uri, &server_index, hashes)
        });

        Self { server, index }
    }

    /// The Simple API index URL (e.g., `http://127.0.0.1:PORT/simple/`).
    pub fn index_url(&self) -> String {
        format!("{}/simple/", self.server.url())
    }

    /// Return the URL for a generated distribution file.
    pub fn file_url(&self, filename: &str) -> String {
        format!("{}/files/{filename}", self.server.url())
    }

    /// Return the filename and advertised SHA-256 digest of each file listed by the index.
    pub fn files(&self) -> impl Iterator<Item = (&str, &str)> {
        self.index
            .packages
            .values()
            .flatten()
            .map(|file| (file.filename.as_str(), file.sha256.as_str()))
    }
}

impl ServerIndex {
    /// Build the index from scenario packages and cached build dependencies.
    fn new(scenario: &Scenario) -> Self {
        let mut index = Self::default();

        for (package_name, package) in &scenario.packages {
            // List packages even when they have no files.
            index.packages.insert(package_name.clone(), Vec::new());

            for (version, meta) in &package.versions {
                let wheel = WheelBuilder::new(package_name, version)
                    .requires(&meta.requires)
                    .extras(&meta.extras)
                    .requires_python(meta.requires_python.as_ref())
                    .entry_points(&meta.entry_points);
                if let Some(wheel_metadata) = &meta.wheel {
                    for tag in wheel_tags(&meta.wheel_tags) {
                        index.register_generated(
                            package_name,
                            wheel.tag(tag).build(),
                            Some((meta, wheel_metadata)),
                        );
                    }
                }

                if let Some(variants) = &meta.variants {
                    let default_artifact = ArtifactMetadata::default();
                    let artifact = meta.wheel.as_ref().unwrap_or(&default_artifact);
                    for (label, variant) in &variants.wheels {
                        let metadata = variant_metadata(variants, [(label, variant)]);
                        let wheel = wheel
                            .requires(variant.requires.as_deref().unwrap_or(&meta.requires))
                            .variant(label, &metadata);
                        let tags = if variant.wheel_tags.is_empty() {
                            &meta.wheel_tags
                        } else {
                            &variant.wheel_tags
                        };
                        for tag in wheel_tags(tags) {
                            index.register_generated(
                                package_name,
                                wheel.tag(tag).build(),
                                Some((meta, artifact)),
                            );
                        }
                    }
                    index.register_generated(
                        package_name,
                        (
                            format!(
                                "{}-{version}-variants.json",
                                package_name.as_dist_info_name()
                            ),
                            variant_metadata(variants, &variants.wheels).into_bytes(),
                        ),
                        None,
                    );
                }

                if let Some(sdist_metadata) = &meta.sdist {
                    index.register_generated(
                        package_name,
                        generate_sdist(
                            package_name,
                            version,
                            &meta.requires,
                            &meta.extras,
                            meta.requires_python.as_ref(),
                            &meta.entry_points,
                        ),
                        Some((meta, sdist_metadata)),
                    );
                }
            }
        }

        for artifact in vendor_artifacts() {
            if !Path::new(artifact.filename)
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("whl"))
            {
                continue;
            }

            let wheel_filename =
                WheelFilename::from_str(artifact.filename).expect("invalid vendor wheel filename");

            index.register_file(
                wheel_filename.name,
                IndexFile {
                    filename: artifact.filename.to_string(),
                    sha256: artifact.sha256.to_string(),
                    distribution: Some(DistributionMetadata::default()),
                },
                FileData::Vendor(artifact),
            );
        }

        index
    }

    fn register_generated(
        &mut self,
        package_name: &PackageName,
        (filename, bytes): (String, Vec<u8>),
        distribution: Option<(&PackageMetadata, &ArtifactMetadata)>,
    ) {
        let sha256 = sha256_hex(&bytes);
        self.register_file(
            package_name.clone(),
            IndexFile {
                filename,
                sha256,
                distribution: distribution.map(|(package, artifact)| DistributionMetadata {
                    requires_python: package.requires_python.clone(),
                    upload_time: artifact.upload_time.clone(),
                    yanked: package.yanked,
                }),
            },
            FileData::Bytes(bytes.into()),
        );
    }

    /// Register a file for download and list it in the Simple API.
    fn register_file(&mut self, package_name: PackageName, file: IndexFile, data: FileData) {
        self.files.insert(file.filename.clone(), data);
        self.packages.entry(package_name).or_default().push(file);
    }
}

fn wheel_tags(tags: &[WheelTag]) -> impl Iterator<Item = &str> {
    tags.iter()
        .map(WheelTag::as_str)
        .chain(tags.is_empty().then_some(DEFAULT_WHEEL_TAG))
}

fn variant_metadata<'a>(
    variants: &Variants,
    wheels: impl IntoIterator<Item = (&'a VariantLabel, &'a VariantWheel)>,
) -> String {
    let properties = wheels
        .into_iter()
        .map(|(label, wheel)| (label, &wheel.properties))
        .collect::<BTreeMap<_, _>>();
    let schema = if variants.providers.is_some() {
        PEP_850_SCHEMA
    } else {
        PEP_825_SCHEMA
    };
    let mut metadata = json!({
        "$schema": schema,
        "default-priorities": { "namespace": variants.namespaces },
        "variants": properties,
    });
    if let Some(providers) = &variants.providers {
        metadata["providers"] = json!(providers);
    }
    metadata.to_string()
}

fn handle_request(
    req: &Request,
    server_uri: &str,
    index: &ServerIndex,
    hashes: bool,
) -> ResponseTemplate {
    let path = req.url.path();

    if let Some(pkg) = extract_package_name(path) {
        let Ok(package_name) = PackageName::from_str(pkg) else {
            return ResponseTemplate::new(404);
        };

        if let Some(entry) = index.packages.get(&package_name) {
            return build_simple_api_response(pkg, entry, server_uri, hashes);
        }
        return ResponseTemplate::new(404);
    }

    if let Some(filename) = path.strip_prefix("/files/") {
        if let Some(file) = index.files.get(filename) {
            return match file.bytes() {
                Ok(bytes) => distribution_file_response(req, filename, &bytes),
                Err(error) => ResponseTemplate::new(500).set_body_string(format!("{error:#}")),
            };
        }
        return ResponseTemplate::new(404);
    }

    ResponseTemplate::new(404)
}

/// Build a response for a distribution file, including support for single byte ranges.
pub fn distribution_file_response(req: &Request, filename: &str, bytes: &[u8]) -> ResponseTemplate {
    let content_type = content_type_for_filename(filename);
    let Some(range) = req.headers.get("range") else {
        return ResponseTemplate::new(200)
            .insert_header("Accept-Ranges", "bytes")
            .set_body_raw(bytes.to_vec(), content_type);
    };

    let Some((start, end)) = range
        .to_str()
        .ok()
        .and_then(|range| parse_byte_range(range, bytes.len()))
    else {
        return ResponseTemplate::new(416)
            .insert_header("Accept-Ranges", "bytes")
            .insert_header("Content-Range", format!("bytes */{}", bytes.len()));
    };

    ResponseTemplate::new(206)
        .insert_header("Accept-Ranges", "bytes")
        .insert_header(
            "Content-Range",
            format!("bytes {start}-{end}/{}", bytes.len()),
        )
        .set_body_raw(bytes[start..=end].to_vec(), content_type)
}

/// Mount a distribution that serves different bytes to range and full-file requests.
///
/// `HEAD` responses advertise range support. Ranged `GET` requests receive the ranged bytes,
/// while full `GET` requests receive the full-file bytes instead.
pub async fn mount_mismatched_distribution(
    server: &MockServer,
    file_path: &str,
    filename: &str,
    ranged_bytes: Vec<u8>,
    full_bytes: Vec<u8>,
) {
    Mock::given(method("HEAD"))
        .and(path(file_path))
        .respond_with(
            ResponseTemplate::new(200)
                .insert_header("Accept-Ranges", "bytes")
                .set_body_bytes(ranged_bytes.clone()),
        )
        .mount(server)
        .await;

    let filename = filename.to_string();
    Mock::given(method("GET"))
        .and(path(file_path))
        .and(header_exists("range"))
        .respond_with(move |request: &Request| {
            distribution_file_response(request, &filename, &ranged_bytes)
        })
        .with_priority(1)
        .expect(1..)
        .mount(server)
        .await;

    Mock::given(method("GET"))
        .and(path(file_path))
        .respond_with(ResponseTemplate::new(200).set_body_bytes(full_bytes))
        .mount(server)
        .await;
}

/// Parse a single HTTP byte range and return its inclusive bounds.
fn parse_byte_range(range: &str, length: usize) -> Option<(usize, usize)> {
    let range = range.strip_prefix("bytes=")?;
    let (start, end) = range.split_once('-')?;

    if start.is_empty() {
        let suffix = end.parse::<usize>().ok()?;
        if suffix == 0 || length == 0 {
            return None;
        }
        return Some((length.saturating_sub(suffix), length - 1));
    }

    let start = start.parse::<usize>().ok()?;
    if start >= length {
        return None;
    }
    let end = if end.is_empty() {
        length - 1
    } else {
        end.parse::<usize>().ok()?.min(length - 1)
    };
    if start > end {
        return None;
    }
    Some((start, end))
}

/// Build PEP 691 JSON response for a package.
fn build_simple_api_response(
    package_name: &str,
    entry: &[IndexFile],
    server_uri: &str,
    hashes: bool,
) -> ResponseTemplate {
    let files: Vec<serde_json::Value> = entry
        .iter()
        .map(|file| {
            let url = format!("{server_uri}/files/{}", file.filename);
            let mut file_obj = json!({
                "filename": file.filename,
                "url": url,
                "hashes": {},
            });
            if hashes {
                file_obj["hashes"] = json!({ "sha256": file.sha256 });
            }
            // `variants.json` is listed alongside distributions without these attributes.
            if let Some(distribution) = &file.distribution {
                file_obj["upload-time"] = json!(
                    distribution
                        .upload_time
                        .as_deref()
                        .unwrap_or(PACKSE_UPLOAD_TIME)
                );
                if let Some(requires_python) = &distribution.requires_python {
                    file_obj["requires-python"] = json!(requires_python);
                }
                if distribution.yanked {
                    file_obj["yanked"] = json!(true);
                }
            }
            file_obj
        })
        .collect();

    let body = json!({
        "meta": { "api-version": "1.1" },
        "name": package_name,
        "files": files,
    });

    let body_str = body.to_string();
    ResponseTemplate::new(200)
        .insert_header("Content-Type", "application/vnd.pypi.simple.v1+json")
        .set_body_raw(body_str, "application/vnd.pypi.simple.v1+json")
}

/// Extract the package name from `/simple/{package}` or `/simple/{package}/`.
fn extract_package_name(path: &str) -> Option<&str> {
    let rest = path.strip_prefix("/simple/")?;
    let pkg = rest.strip_suffix('/').unwrap_or(rest);
    if pkg.is_empty() || pkg.contains('/') {
        return None;
    }
    Some(pkg)
}

#[cfg(test)]
mod tests {
    use anyhow::Result;
    use reqwest::StatusCode;
    use reqwest::header::{ACCEPT_RANGES, CONTENT_RANGE, RANGE};
    use wiremock::MockServer;

    use crate::vendor::vendor_artifacts;

    use super::{
        PackseServer, Scenario, ServerIndex, extract_package_name, mount_mismatched_distribution,
    };

    #[test]
    fn extract_package_name_accepts_with_or_without_trailing_slash() {
        assert_eq!(extract_package_name("/simple/foo/"), Some("foo"));
        assert_eq!(extract_package_name("/simple/foo"), Some("foo"));
    }

    #[test]
    fn extract_package_name_rejects_invalid_paths() {
        assert_eq!(extract_package_name("/simple/"), None);
        assert_eq!(extract_package_name("/simple"), None);
        assert_eq!(extract_package_name("/simple/foo/bar"), None);
    }

    #[test]
    fn server_index_construction_does_not_load_vendor_artifacts() {
        let _index = ServerIndex::new(&Scenario::empty());

        assert!(
            vendor_artifacts()
                .iter()
                .all(|artifact| !artifact.is_loaded())
        );
    }

    #[tokio::test]
    async fn serves_artifact_upload_times() -> Result<()> {
        let scenario = toml::from_str::<Scenario>(
            r#"
name = "artifact-upload-times"

[root]
requires = ["a"]

[expected]
satisfiable = true

[packages.a.versions."1.0.0"]
sdist = { upload_time = "2024-03-23T00:00:00Z" }
wheel = { upload_time = "2024-03-26T00:00:00Z" }
wheel_tags = ["py3-none-any", "cp312-abi3-win_amd64"]

[packages.b.versions."1.0.0"]
sdist = false
wheel = {}

[packages.c.versions."1.0.0"]
wheel = false
"#,
        )?;
        let server = PackseServer::from_scenario(&scenario);

        let a: serde_json::Value = reqwest::get(format!("{}a/", server.index_url()))
            .await?
            .json()
            .await?;
        assert_eq!(a["files"].as_array().map(Vec::len), Some(3));
        assert_eq!(a["files"][0]["filename"], "a-1.0.0-py3-none-any.whl");
        assert_eq!(a["files"][0]["upload-time"], "2024-03-26T00:00:00Z");
        assert_eq!(
            a["files"][1]["filename"],
            "a-1.0.0-cp312-abi3-win_amd64.whl"
        );
        assert_eq!(a["files"][1]["upload-time"], "2024-03-26T00:00:00Z");
        assert_eq!(a["files"][2]["filename"], "a-1.0.0.tar.gz");
        assert_eq!(a["files"][2]["upload-time"], "2024-03-23T00:00:00Z");

        let b: serde_json::Value = reqwest::get(format!("{}b/", server.index_url()))
            .await?
            .json()
            .await?;
        assert_eq!(b["files"].as_array().map(Vec::len), Some(1));
        assert_eq!(b["files"][0]["filename"], "b-1.0.0-py3-none-any.whl");
        assert_eq!(b["files"][0]["upload-time"], "2024-03-24T00:00:00Z");

        let c: serde_json::Value = reqwest::get(format!("{}c/", server.index_url()))
            .await?
            .json()
            .await?;
        assert_eq!(c["files"].as_array().map(Vec::len), Some(1));
        assert_eq!(c["files"][0]["filename"], "c-1.0.0.tar.gz");
        assert_eq!(c["files"][0]["upload-time"], "2024-03-24T00:00:00Z");

        Ok(())
    }

    #[tokio::test]
    async fn file_requests_support_byte_ranges() -> Result<()> {
        let scenario = toml::from_str::<Scenario>(
            r#"
name = "range-requests"

[root]
requires = ["a"]

[expected]
satisfiable = true

[packages.a.versions."1.0.0"]
sdist = false
"#,
        )?;
        let server = PackseServer::from_scenario(&scenario);
        let url = server.file_url("a-1.0.0-py3-none-any.whl");
        let client = reqwest::Client::new();

        let response = client.get(&url).send().await?;
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(
            response.headers().get(ACCEPT_RANGES),
            Some(&"bytes".parse()?)
        );
        let bytes = response.bytes().await?;
        let length = bytes.len();

        let response = client.get(&url).header(RANGE, "bytes=-8").send().await?;
        assert_eq!(response.status(), StatusCode::PARTIAL_CONTENT);
        assert_eq!(
            response.headers().get(CONTENT_RANGE),
            Some(&format!("bytes {}-{}/{}", length - 8, length - 1, length).parse()?)
        );
        assert_eq!(response.bytes().await?, bytes[length - 8..]);

        let response = client
            .get(&url)
            .header(RANGE, "bytes=-999999")
            .send()
            .await?;
        assert_eq!(response.status(), StatusCode::PARTIAL_CONTENT);
        assert_eq!(
            response.headers().get(CONTENT_RANGE),
            Some(&format!("bytes 0-{}/{}", length - 1, length).parse()?)
        );
        assert_eq!(response.bytes().await?, bytes);

        let response = client.get(&url).header(RANGE, "bytes=3-9").send().await?;
        assert_eq!(response.status(), StatusCode::PARTIAL_CONTENT);
        assert_eq!(
            response.headers().get(CONTENT_RANGE),
            Some(&format!("bytes 3-9/{length}").parse()?)
        );
        assert_eq!(response.bytes().await?, bytes[3..=9]);

        let response = client.get(&url).header(RANGE, "bytes=10-").send().await?;
        assert_eq!(response.status(), StatusCode::PARTIAL_CONTENT);
        assert_eq!(
            response.headers().get(CONTENT_RANGE),
            Some(&format!("bytes 10-{}/{}", length - 1, length).parse()?)
        );
        assert_eq!(response.bytes().await?, bytes[10..]);

        let response = client
            .get(&url)
            .header(RANGE, format!("bytes={length}-"))
            .send()
            .await?;
        assert_eq!(response.status(), StatusCode::RANGE_NOT_SATISFIABLE);
        assert_eq!(
            response.headers().get(CONTENT_RANGE),
            Some(&format!("bytes */{length}").parse()?)
        );

        Ok(())
    }

    #[tokio::test]
    async fn mismatched_distribution_serves_ranged_and_full_bytes() -> Result<()> {
        let server = MockServer::start().await;
        mount_mismatched_distribution(
            &server,
            "/files/example.whl",
            "example.whl",
            b"forged".to_vec(),
            b"authentic".to_vec(),
        )
        .await;
        let url = format!("{}/files/example.whl", server.uri());
        let client = reqwest::Client::new();

        let response = client.head(&url).send().await?;
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(
            response.headers().get(ACCEPT_RANGES),
            Some(&"bytes".parse()?)
        );

        let response = client.get(&url).header(RANGE, "bytes=1-3").send().await?;
        assert_eq!(response.status(), StatusCode::PARTIAL_CONTENT);
        assert_eq!(response.bytes().await?, b"org".as_slice());

        let response = client.get(&url).send().await?;
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(response.bytes().await?, b"authentic".as_slice());

        Ok(())
    }
}
